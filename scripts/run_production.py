"""
Production runner: apply the fine-tuned model + fallback to the entire corpus.

Processes all pages that have HTR raw output (generated by Balakirev),
corrects with the fine-tuned model, applies fallback if needed, and
saves results as JSON files compatible with diff_html.py.

Includes checkpointing: if interrupted, can be resumed from where it
left off. The checkpoint tracks which pages have been processed.

Fallback mechanism:
    1. Truncation: if output is >10% shorter than input, revert.
    2. CER regression: if GT is available and CER worsens, revert.

Usage:
    python scripts/run_production.py \\
        --model models/finetuned \\
        --htr data/htr_raw \\
        --output data/corrected
"""

import argparse
import json
import logging
import sys
import time
from datetime import datetime
from pathlib import Path

import torch
from peft import PeftModel
from transformers import AutoModelForCausalLM, AutoTokenizer

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.parsers.alto_parser import parse_alto_file
from src.evaluation.metrics import calculate_cer

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.StreamHandler(),
        logging.FileHandler("logs/production.log"),
    ],
)
logger = logging.getLogger(__name__)


# ─── Prompt (must match fine-tuning; kept in Catalan) ────────────────────────────────────────────────────────────────────

SYSTEM_PROMPT = (
    "Ets un expert en post-correcció d'HTR dels diaris de Ramon Viñes. "
    "Corregeix els errors de reconeixement del text manuscrit. "
    "Només corregeix errors d'HTR evidents. No modifiquis l'ortografia "
    "de l'autor, noms propis, ni símbols especials (¶, ¬, ⟦ ⟧). "
    "Si no estàs segur d'una correcció, deixa la paraula original."
)


# ─── Checkpoint ────────────────────────────────────────────────────────────────

def load_checkpoint(checkpoint_path):
    """Load the set of already-processed page IDs."""
    try:
        with open(checkpoint_path, encoding="utf-8") as f:
            data = json.load(f)
            return set(data.get("processed", []))
    except FileNotFoundError:
        return set()


def save_checkpoint(checkpoint_path, processed):
    """Save the current checkpoint state."""
    Path(checkpoint_path).parent.mkdir(parents=True, exist_ok=True)
    with open(checkpoint_path, "w", encoding="utf-8") as f:
        json.dump({
            "processed": sorted(processed),
            "last_updated": datetime.now().isoformat(),
            "total": len(processed),
        }, f, indent=2)


# ─── Model loading ─────────────────────────────────────────────────────────────────────

def load_model(model_path):
    """Load the base model + LoRA adapters from the fine-tuned directory."""
    logger.info(f"Loading model from {model_path}...")

    config_path = Path(model_path) / "finetune_config.json"
    if config_path.exists():
        with open(config_path) as f:
            config = json.load(f)
        base_model_name = config.get("config", {}).get("model", {}).get("name", "")
        token = config.get("config", {}).get("model", {}).get("access_token", "") or None
    else:
        base_model_name = ""
        token = None

    tokenizer = AutoTokenizer.from_pretrained(model_path, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    if base_model_name:
        logger.info(f"  Model base: {base_model_name}")
        base_model = AutoModelForCausalLM.from_pretrained(
            base_model_name, token=token, trust_remote_code=True,
            device_map="auto", torch_dtype=torch.bfloat16,
        )
        logger.info(f"  Loading LoRA adapters...")
        model = PeftModel.from_pretrained(base_model, model_path)
    else:
        model = AutoModelForCausalLM.from_pretrained(
            model_path, trust_remote_code=True,
            device_map="auto", torch_dtype=torch.bfloat16,
        )

    model.eval()
    return model, tokenizer


# ─── Correcció + Fallback ──────────────────────────────────────────────────────

def correct_text(model, tokenizer, htr_text, max_new_tokens=4096):
    """Correct an HTR text using the fine-tuned model (greedy decoding)."""
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"Corregeix el següent text HTR:\n{htr_text}"},
    ]

    text = tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True,
        enable_thinking=False,
    )

    inputs = tokenizer(text, return_tensors="pt").to(model.device)

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False,
            temperature=1.0,
            pad_token_id=tokenizer.pad_token_id,
        )

    generated = outputs[0][inputs["input_ids"].shape[-1]:]
    response = tokenizer.decode(generated, skip_special_tokens=True)

    return response.strip()


def apply_fallback(htr_text, corrected_text, gt_text=None, max_length_loss=0.10):
    """
    Revert to original if the output is truncated or worsens CER.

    Args:
        htr_text: original HTR text.
        corrected_text: model output.
        gt_text: ground truth (optional, enables CER check).
        max_length_loss: maximum allowed length reduction (default 10%).

    Returns:
        tuple (final_text, fallback_applied, reason)
    """
    input_len = len(htr_text)
    output_len = len(corrected_text)

    # Criteria 1: truncation
    if output_len < input_len * (1 - max_length_loss):
        reason = f"truncament ({output_len}/{input_len} chars, -{100*(1-output_len/input_len):.0f}%)"
        return htr_text, True, reason

    # Criteria 2: CER worsens (when GT is available)
    if gt_text and len(gt_text.strip()) > 0:
        cer_before = calculate_cer(gt_text, htr_text)
        cer_after = calculate_cer(gt_text, corrected_text)
        if cer_after > cer_before:
            reason = f"CER worsens ({cer_before:.2%} → {cer_after:.2%})"
            return htr_text, True, reason

    return corrected_text, False, ""


# ─── Main Pipeline ──────────────────────────────────────────────────────────────────

def run_production(model_path, htr_dir, output_dir):
    htr_dir = Path(htr_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    checkpoint_path = output_dir / "checkpoint.json"

    Path("logs").mkdir(exist_ok=True)

    model, tokenizer = load_model(model_path)

    # Checkpoint
    processed = load_checkpoint(checkpoint_path)
    logger.info(f"Pages already processed: {len(processed)}")

    # Find all HTR raw pages (organised by year)
    all_pages = []
    for year_dir in sorted(htr_dir.iterdir()):
        if not year_dir.is_dir():
            continue
        for xml_file in sorted(year_dir.glob("*.xml")):
            page_id = f"{year_dir.name}/{xml_file.stem}"
            all_pages.append((page_id, xml_file))

    pending = [(pid, f) for pid, f in all_pages if pid not in processed]
    logger.info(f"Total pages: {len(all_pages)} | Pending: {len(pending)}")

    if not pending:
        logger.info("All pages already processed.")
        return

    # Process
    start_time = datetime.now()
    errors = 0
    fallbacks = 0
    total_cer_reduction = 0

    for i, (page_id, xml_file) in enumerate(pending):
        logger.info(f"[{i+1}/{len(pending)}] {page_id}")

        try:
            # Parse HTR raw
            parsed = parse_alto_file(xml_file)
            htr_lines = [l["text"] for l in parsed["lines"]]
            htr_text = " ".join(htr_lines)

            if len(htr_text.strip()) < 10:
                logger.info(f"  Text too short ({len(htr_text)} chars), skipping")
                processed.add(page_id)
                save_checkpoint(checkpoint_path, processed)
                continue

            # Correct
            page_start = time.time()
            corrected_text = correct_text(model, tokenizer, htr_text)
            elapsed = time.time() - page_start

            # Load GT if available (for CER-based fallback)
            gt_text = None
            year = page_id.split("/")[0]
            page_name = page_id.split("/")[1]
            gt_file = Path(f"/gt/{year}/{page_name}.xml")
            if gt_file.exists():
                try:
                    gt_parsed = parse_alto_file(gt_file)
                    gt_text = " ".join([l["text"] for l in gt_parsed["lines"]])
                except Exception:
                    pass

            # Fallback (truncation + CER if GT available)
            final_text, is_fallback, fallback_reason = apply_fallback(
                htr_text, corrected_text, gt_text
            )

            if is_fallback:
                fallbacks += 1
                logger.info(f"  ⟲ FALLBACK: {fallback_reason} [{elapsed:.1f}s]")
            else:
                # Count changes
                changes = sum(1 for a, b in zip(htr_text.split(), final_text.split()) if a != b)
                logger.info(f"  ✓ {changes} changes [{elapsed:.1f}s]")

            # Save result (format compatible with diff_html.py)
            year = page_id.split("/")[0]
            page_output_dir = output_dir / year
            page_output_dir.mkdir(parents=True, exist_ok=True)

            result = {
                "page": page_id,
                "model": "Qwen3-8B-finetuned-LoRA",
                "strategy": "fullpage_with_fallback",
                "timestamp": datetime.now().isoformat(),
                "fallback": is_fallback,
                "fallback_reason": fallback_reason,
                "time_seconds": round(elapsed, 1),
                "lines": [
                    {
                        "line_id": line["line_id"],
                        "esc_id": line.get("esc_id", ""),
                        "text_original": line["text"],
                        "text_corrected": line["text"],  # per line: kept as-is
                    }
                    for line in parsed["lines"]
                ],
                "fulltext_original": htr_text,
                "fulltext_corrected": final_text,
            }

            output_file = page_output_dir / f"{xml_file.stem}.json"
            with open(output_file, "w", encoding="utf-8") as f:
                json.dump(result, f, indent=2, ensure_ascii=False)

            # Update checkpoint
            processed.add(page_id)
            save_checkpoint(checkpoint_path, processed)

        except Exception as e:
            errors += 1
            logger.error(f"  ERROR: {e}")

    # Resum
    elapsed_total = datetime.now() - start_time
    logger.info(f"\n{'='*60}")
    logger.info(f"PRODUCTION COMPLETE")
    logger.info(f"{'='*60}")
    logger.info(f"Processed: {len(pending) - errors}")
    logger.info(f"Fallbacks: {fallbacks}")
    logger.info(f"Errors: {errors}")
    logger.info(f"Total time: {elapsed_total}")
    if len(pending) - errors > 0:
        logger.info(f"Average per page: {elapsed_total / (len(pending) - errors)}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Production: correct entire corpus")
    parser.add_argument("--model", default="models/finetuned")
    parser.add_argument("--htr", default="data/htr_raw")
    parser.add_argument("--output", default="data/corrected")
    args = parser.parse_args()

    run_production(args.model, args.htr, args.output)
